/**
 * Expo config plugin: Android network security configuration.
 *
 * Release (main source set):
 *   - Cleartext (http://) traffic is forbidden everywhere.
 *   - Only system CAs are trusted.
 *
 * Debug (debug source set overlay, applied only to debug builds):
 *   - Cleartext is allowed ONLY for the Metro bundler hosts (localhost via adb reverse).
 *   - <debug-overrides> additionally trusts the local mkcert root CA, so the dev API's
 *     certificate validates. Android honours <debug-overrides> only when the app is debuggable.
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RESOURCE_NAME = 'network_security_config';
const CA_RESOURCE = 'dev_ca';

function releaseXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidNetworkSecurity.js. Do not edit. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;
}

function escapeXml(value) {
  return value.replace(/[<>&"']/g, (c) => `&#${c.charCodeAt(0)};`);
}

function debugXml({ hasCa, cleartextHosts }) {
  const domains = cleartextHosts
    .map((host) => `        <domain includeSubdomains="false">${escapeXml(host)}</domain>`)
    .join('\n');
  const caAnchor = hasCa ? `\n            <certificates src="@raw/${CA_RESOURCE}" />` : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidNetworkSecurity.js. DEBUG BUILDS ONLY. Do not edit. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <!-- Metro bundler (development only). The API is never reached over cleartext. -->
    <domain-config cleartextTrafficPermitted="true">
${domains}
    </domain-config>
    <debug-overrides>
        <trust-anchors>
            <certificates src="system" />${caAnchor}
        </trust-anchors>
    </debug-overrides>
</network-security-config>
`;
}

function writeFile(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

/**
 * @param {import('expo/config').ExpoConfig} config
 * @param {{ caFile?: string; debugCleartextHosts?: string[] }} options
 */
function withAndroidNetworkSecurity(config, options = {}) {
  const { caFile, debugCleartextHosts = ['localhost', '127.0.0.1'] } = options;

  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    // On API 24+ this overrides android:usesCleartextTraffic entirely.
    app.$['android:networkSecurityConfig'] = `@xml/${RESOURCE_NAME}`;
    return cfg;
  });

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const androidRoot = cfg.modRequest.platformProjectRoot;
      const mainRes = path.join(androidRoot, 'app', 'src', 'main', 'res');
      const debugRes = path.join(androidRoot, 'app', 'src', 'debug', 'res');

      writeFile(path.join(mainRes, 'xml', `${RESOURCE_NAME}.xml`), releaseXml());

      const caPath = caFile ? path.resolve(cfg.modRequest.projectRoot, caFile) : undefined;
      const hasCa = Boolean(caPath && fs.existsSync(caPath));
      const caTarget = path.join(debugRes, 'raw', `${CA_RESOURCE}.pem`);
      if (hasCa) {
        writeFile(caTarget, fs.readFileSync(caPath));
      } else {
        if (fs.existsSync(caTarget)) fs.rmSync(caTarget);
        console.warn(
          `[withAndroidNetworkSecurity] Dev CA not found at ${caPath ?? '(not configured)'}. ` +
            'Run "npm run certs" at the repo root, then rebuild, or HTTPS to the dev API will fail.',
        );
      }

      writeFile(
        path.join(debugRes, 'xml', `${RESOURCE_NAME}.xml`),
        debugXml({ hasCa, cleartextHosts: debugCleartextHosts }),
      );
      return cfg;
    },
  ]);

  return config;
}

module.exports = withAndroidNetworkSecurity;
